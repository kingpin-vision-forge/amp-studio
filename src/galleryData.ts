export function albumPhotos(album: GalleryAlbum): GalleryPhoto[] {
  return album.shoots.flatMap((s) => s.photos);
}

/** First landscape photo in the album, used as its Selected Work cover. */
export function albumCover(id: string): string {
  const photos = albumPhotos(albums[id]);
  return (photos.find((p) => p.w > p.h) ?? photos[0]).src;
}

/**
 * Pick `count` photos of one orientation, spread evenly through the album so they
 * come from different shoots. `skipFirst` leaves out the first match (the cover).
 */
export function albumPick(
  id: string,
  orientation: "portrait" | "landscape",
  count: number,
  skipFirst = false,
): GalleryPhoto[] {
  const pool = albumPhotos(albums[id])
    .filter((p) => (orientation === "portrait" ? p.h > p.w : p.w > p.h))
    .slice(skipFirst ? 1 : 0);
  if (pool.length <= count) return pool;
  return Array.from({ length: count }, (_, i) => pool[Math.floor((i * pool.length) / count)]);
}
